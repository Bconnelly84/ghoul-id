const fs = require('fs');
const assert = require('assert');
const app = fs.readFileSync('App.js', 'utf8');
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const expo = JSON.parse(fs.readFileSync('app.json', 'utf8'));
const { parseBarcodeCandidate, getBarcodeBounds } = require('../../scanner-utils');

assert.match(app, /CameraView[\s\S]*onBarcodeScanned=\{handleBarcodeDetected\}/, 'Scanner must use live barcode detection');
assert.doesNotMatch(app, /takePictureAsync\s*\(/, 'Live scanner must not take repeated photos');
assert.doesNotMatch(app, /setInterval\s*\([\s\S]{0,160}runLiveOcr/, 'No periodic OCR loop should run in the scanner');
assert.match(app, /SCAN_DELAY_OPTIONS\s*=\s*\[500, 900, 1500, 2000\]/, 'Delay choices should remain configurable');
assert.match(app, /BATCH_SESSION_KEY\s*=\s*'ghoul-id-active-scan-session-v1'/, 'Batch session must have its own local storage key');
assert.match(app, /AsyncStorage\.setItem\(BATCH_SESSION_KEY/, 'Batch session should be persisted locally');
assert.match(app, /AsyncStorage\.getItem\(BATCH_SESSION_KEY/, 'Batch session should be restored locally');
assert.match(app, /SESSION QUEUE/, 'Scanner should show a persistent session queue');
assert.match(app, /setBatchDuplicateCount/, 'Repeated barcode detections should be counted instead of duplicated');
assert.match(app, /LOOK UP SELECTED CODE/, 'Selected code lookup action must be visible');
assert.match(app, /CHECK ALL AGAINST CATALOG/, 'Batch should support checking every code against the local catalog');
assert.match(app, /OTHER LOOKUP OPTIONS/, 'Alternative lookup options should be expandable');
assert.match(app, /<ScrollView style=\{\{ flex: 1 \}\} contentContainerStyle=\{\[styles\.scanScreen/, 'Whole scanner screen should scroll with camera in page flow');
assert.match(app, /hardwareBackPress/, 'Android hardware Back should be handled by app navigation');
assert.match(app, /SORT CATALOG/, 'Catalog should provide sort controls');
assert.match(app, /PHOTO FALLBACK: READ PRINTED TEXT/, 'OCR should remain an explicit fallback');
assert.strictEqual(pkg.version, '2.8.0');
assert.strictEqual(expo.expo.version, '2.8.0');
assert.strictEqual(expo.expo.android.versionCode, 20);

assert.deepStrictEqual(parseBarcodeCandidate('194735256648'), {raw:'194735256648', digits:'194735256648', checksumValid:true});
assert.deepStrictEqual(parseBarcodeCandidate('194735333367'), {raw:'194735333367', digits:'194735333367', checksumValid:false});
assert.strictEqual(parseBarcodeCandidate('JHK55'), null);
assert.deepStrictEqual(getBarcodeBounds({cornerPoints:[{x:20,y:30},{x:120,y:30},{x:120,y:70},{x:20,y:70}]}), {origin:{x:20,y:30},size:{width:100,height:40}});
assert.deepStrictEqual(getBarcodeBounds({bounds:{x:5,y:10,width:50,height:20}}), {origin:{x:5,y:10},size:{width:50,height:20}});
assert.deepStrictEqual(getBarcodeBounds({bounds:{origin:{x:1,y:2},size:{width:3,height:4}}}), {origin:{x:1,y:2},size:{width:3,height:4}});
console.log('Batch scanner regression checks passed.');
